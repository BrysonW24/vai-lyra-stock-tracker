type Bar = { label: string; v: number; c: string };

function PrecisionBars({ verdicts }: { verdicts: EvidenceVerdict[] }) {
  const ch = champion(verdicts);
  const held = verdicts.find((v) => v.model === 'challenger' && v.split === 'holdout');
  const ref = verdicts.find((v) => v.model === 'reference_scorecard' && v.split === 'holdout');
  const raw: (Bar | null)[] = [
    ch && ch.precisionAtK != null ? { label: 'champion', v: ch.precisionAtK, c: C.champion } : null,
    held && held.precisionAtK != null ? { label: 'challenger', v: held.precisionAtK, c: C.challenger } : null,
    ref && ref.precisionAtK != null ? { label: 'reference', v: ref.precisionAtK, c: C.refuted } : null,
  ];
  const bars = raw.filter((b): b is Bar => b !== null);
  const base = ch?.baseRate ?? null;
  if (!bars.length) return null;
  const W = 340;
  const H = 210;
  const padT = 16;
  const padB = 30;
  const ymax = Math.max(0.3, ...bars.map((b) => b.v), base ?? 0) * 1.1;
  const plotH = H - padT - padB;
  const Y = (v: number) => padT + plotH - (v / ymax) * plotH;
  const gap = W / bars.length;
  const bw = gap * 0.42;
  return (
    <svg viewBox={`0 0 ${W} ${H}`} className="block h-auto w-full font-mono" role="img" aria-label="Holdout top-pick doubler share by model against the random base rate">
      {base != null ? (
        <>
          <line x1={0} y1={Y(base)} x2={W} y2={Y(base)} style={{ stroke: C.nul }} strokeWidth={1.5} strokeDasharray="4 3" />
          <text x={W - 4} y={Y(base) - 6} textAnchor="end" fontSize={10.5} style={{ fill: C.nul }}>{`random ${fmtPct(base)}`}</text>
        </>
      ) : null}
      {bars.map((b, i) => {
        const cx = gap * (i + 0.5);
        const yTop = Y(b.v);
        return (
          <g key={b.label}>
            <title>{`${b.label}: ${fmtPct(b.v)} doubled${base != null ? ` vs ${fmtPct(base)} random` : ''}`}</title>
            <rect x={cx - bw / 2} y={yTop} width={bw} height={padT + plotH - yTop} rx={4} style={{ fill: b.c }} />
            <text x={cx} y={yTop - 8} textAnchor="middle" fontSize={13} fontWeight={600} style={{ fill: b.c }}>{fmtPct(b.v)}</text>
            <text x={cx} y={H - 10} textAnchor="middle" fontSize={11} style={{ fill: C.ink3 }}>{b.label}</text>
          </g>
        );
      })}
    </svg>
  );
}

function CalibrationChart({ bins }: { bins: CalibrationBin[] }) {
  if (bins.length < 2) return null;
  const W = 340;
  const H = 210;
  const pad = 32;
  const hi = Math.max(0.28, ...bins.map((b) => Math.max(b.predicted, b.actual))) * 1.05;
  const plot = W - pad - 14;
  const plotH = H - pad - 14;
  const X = (v: number) => pad + (v / hi) * plot;
  const Y = (v: number) => H - pad - (v / hi) * plotH;
  const grid = [0, 0.1, 0.2].filter((g) => g <= hi);
  const line = bins.map((b) => `${X(b.predicted)},${Y(b.actual)}`).join(' ');
  return (
    <svg viewBox={`0 0 ${W} ${H}`} className="block h-auto w-full font-mono" role="img" aria-label="Reliability curve, predicted versus realised winner rate">
      {grid.map((g) => (
        <g key={`g${g}`}>
          <line x1={X(g)} y1={pad - 14} x2={X(g)} y2={H - pad} style={{ stroke: alpha(R.ink, 0.06) }} strokeWidth={1} />
          <line x1={pad} y1={Y(g)} x2={W - 14} y2={Y(g)} style={{ stroke: alpha(R.ink, 0.06) }} strokeWidth={1} />
          <text x={X(g)} y={H - pad + 14} textAnchor="middle" fontSize={10} style={{ fill: C.ink3 }}>{(g * 100).toFixed(0)}%</text>
          <text x={pad - 6} y={Y(g) + 3} textAnchor="end" fontSize={10} style={{ fill: C.ink3 }}>{(g * 100).toFixed(0)}%</text>
        </g>
      ))}
      <line x1={X(0)} y1={Y(0)} x2={X(hi)} y2={Y(hi)} style={{ stroke: C.nul }} strokeWidth={1.5} strokeDasharray="4 4" />
      <polyline points={line} fill="none" style={{ stroke: C.champion }} strokeWidth={2} strokeLinejoin="round" />
      {bins.map((b) => (
        <circle key={b.bin} cx={X(b.predicted)} cy={Y(b.actual)} r={4} style={{ fill: C.champion, stroke: 'var(--lyra-panel)' }} strokeWidth={1.5}>
          <title>{`predicted ${fmtPct(b.predicted)} - realised ${fmtPct(b.actual)}`}</title>
        </circle>
      ))}
      <text x={pad + 2} y={pad - 6} fontSize={10} style={{ fill: C.ink3 }}>realised rate</text>
      <text x={W - 14} y={H - pad + 14} textAnchor="end" fontSize={10} style={{ fill: C.ink3 }}>predicted</text>
    </svg>
  );
}

function CohortTimeline({ cohorts }: { cohorts: { dev: CohortRow[]; holdout: CohortRow[] } }) {
  const all = [
    ...cohorts.dev.map((r) => ({ ...r, split: 'dev' as const })),
    ...cohorts.holdout.map((r) => ({ ...r, split: 'holdout' as const })),
  ];
  if (!all.length) return null;
  const colW = 26;
  const padT = 18;
  const padB = 44;
  const padL = 38;
  const padR = 12;
  const W = padL + all.length * colW + padR;
  const H = 240;
  const ymax = Math.max(0.5, ...all.map((r) => r.precision_at_k));
  const plotH = H - padT - padB;
  const Y = (v: number) => padT + plotH - (Math.min(v, ymax) / ymax) * plotH;
  const grid = [0, 0.2, 0.4].filter((g) => g <= ymax);
  const bx = padL + cohorts.dev.length * colW;
  return (
    <div className="w-full overflow-x-auto">
      <svg viewBox={`0 0 ${W} ${H}`} width={W} className="block h-auto font-mono" role="img" aria-label="Per-quarter precision against the chance null, dev walk-forward then one-shot holdout">
        {grid.map((g) => (
          <g key={`g${g}`}>
            <line x1={padL} y1={Y(g)} x2={W - padR} y2={Y(g)} style={{ stroke: alpha(R.ink, 0.06) }} strokeWidth={1} />
            <text x={padL - 6} y={Y(g) + 3} textAnchor="end" fontSize={10} style={{ fill: C.ink3 }}>{(g * 100).toFixed(0)}%</text>
          </g>
        ))}
        {cohorts.holdout.length ? (
          <>
            <line x1={bx} y1={padT - 8} x2={bx} y2={padT + plotH} style={{ stroke: C.champion }} strokeWidth={1.5} strokeDasharray="3 3" opacity={0.5} />
            <text x={bx + 4} y={padT - 1} fontSize={10} style={{ fill: C.champion }}>holdout {'→'}</text>
          </>
        ) : null}
        {all.map((d, i) => {
          const cx = padL + i * colW + colW / 2;
          const col = d.split === 'holdout' ? C.champion : C.nul;
          const op = d.split === 'holdout' ? 1 : 0.42;
          const yTop = Y(d.precision_at_k);
          return (
            <g key={`${d.cohort}-${d.split}`}>
              <title>{`${d.cohort} (${d.split}): precision ${fmtPct(d.precision_at_k)}, chance ${fmtPct(d.base_rate)}`}</title>
              <rect x={cx - colW * 0.32} y={yTop} width={colW * 0.64} height={padT + plotH - yTop} rx={3} style={{ fill: col }} opacity={op} />
              <line x1={cx - colW * 0.42} y1={Y(d.base_rate)} x2={cx + colW * 0.42} y2={Y(d.base_rate)} style={{ stroke: C.refuted }} strokeWidth={2} />
              {i % 2 === 0 || d.split === 'holdout' ? (
                <text fontSize={9.5} style={{ fill: C.ink3 }} textAnchor="end" transform={`translate(${cx + 3},${padT + plotH + 10}) rotate(-55)`}>{d.cohort}</text>
              ) : null}
            </g>
          );
        })}
      </svg>
    </div>
  );
}

function WeightFlip({ weights }: { weights: NonNullable<Evidence['weights']> }) {
  const { features, current, baselineSynthetic: syn } = weights;
  const lim = Math.max(0.7, ...current.map((w) => Math.abs(w)), ...syn.map((w) => Math.abs(w)));
  const rowH = 28;
  const padT = 12;
  const padB = 24;
  const padL = 116;
  const padR = 56;
  const W = 720;
  const H = padT + features.length * rowH + padB;
  const plotW = W - padL - padR;
  const midX = padL + plotW / 2;
  const X = (v: number) => midX + (v / lim) * (plotW / 2);
  return (
    <svg viewBox={`0 0 ${W} ${H}`} className="block h-auto w-full font-mono" role="img" aria-label="Standardised logistic weights, synthetic hypothesis versus learned from real outcomes">
      <line x1={midX} y1={padT - 6} x2={midX} y2={H - padB} style={{ stroke: C.nul }} strokeWidth={1.5} />
      {[-0.5, 0.5].map((g) => (
        <g key={`g${g}`}>
          <line x1={X(g)} y1={padT - 6} x2={X(g)} y2={H - padB} style={{ stroke: alpha(R.ink, 0.06) }} strokeWidth={1} />
          <text x={X(g)} y={H - padB + 15} textAnchor="middle" fontSize={10} style={{ fill: C.ink3 }}>{g.toFixed(1)}</text>
        </g>
      ))}
      {features.map((f, i) => {
        const cy = padT + i * rowH + rowH / 2;
        const cur = current[i];
        const s = syn[i];
        const dead = cur === 0;
        const col = cur >= 0 ? C.champion : C.refuted;
        const sx = X(s);
        return (
          <g key={f}>
            <title>{dead ? `${f}: 0.00 - data pipeline unbuilt (never faked)` : `${f}: learned ${cur >= 0 ? '+' : ''}${cur.toFixed(2)}, synthetic ${s >= 0 ? '+' : ''}${s.toFixed(2)}`}</title>
            <text x={padL - 12} y={cy + 3.5} textAnchor="end" fontSize={11.5} style={{ fill: dead ? C.ink3 : C.ink }}>{f.replace(/_/g, ' ')}</text>
            {dead ? (
              <rect x={midX - 5} y={cy - 5} width={10} height={10} rx={2} fill="none" style={{ stroke: C.ink3 }} strokeWidth={1} strokeDasharray="2 2" />
            ) : (
              <rect x={Math.min(X(0), X(cur))} y={cy - 7} width={Math.abs(X(cur) - X(0))} height={14} rx={3} style={{ fill: col }} />
            )}
            <path d={`M ${sx} ${cy - 6} L ${sx + 5} ${cy} L ${sx} ${cy + 6} L ${sx - 5} ${cy} Z`} fill="none" style={{ stroke: C.ink3 }} strokeWidth={1.5} />
          </g>
        );
      })}
    </svg>
  );
}

function LeakageChart({ steps }: { steps: NonNullable<Evidence['leakage']> }) {
  if (!steps.length) return null;
  const W = 720;
  const H = 230;
  const padT = 22;
  const padB = 50;
  const padL = 28;
  const padR = 18;
  const ymax = Math.max(3, ...steps.map((s) => s.lift));
  const plotH = H - padT - padB;
  const Y = (v: number) => padT + plotH - (v / ymax) * plotH;
  const step = (W - padL - padR) / steps.length;
  const linePts = steps.map((s, i) => `${padL + step * (i + 0.5)},${Y(s.lift)}`).join(' ');
  const grid: number[] = [];
  for (let g = 0; g <= ymax + 0.001; g += 1) grid.push(g);
  return (
    <svg viewBox={`0 0 ${W} ${H}`} className="block h-auto w-full font-mono" role="img" aria-label="Leakage decomposition, each fix lowering the lift toward the confirmed number">
      {grid.map((g) => (
        <g key={`g${g}`}>
          <line x1={padL} y1={Y(g)} x2={W - padR} y2={Y(g)} style={{ stroke: alpha(R.ink, 0.06) }} strokeWidth={1} />
          <text x={padL - 6} y={Y(g) + 3} textAnchor="end" fontSize={10} style={{ fill: C.ink3 }}>{g}{'×'}</text>
        </g>
      ))}
      <polyline points={linePts} fill="none" style={{ stroke: C.ink3 }} strokeWidth={1.5} strokeDasharray="3 3" />
      {steps.map((s, i) => {
        const cx = padL + step * (i + 0.5);
        const first = i === 0;
        const col = s.confirm ? C.champion : first ? C.refuted : C.ink2;
        const bw = step * 0.34;
        const yTop = Y(s.lift);
        const words = s.label.split(' ');
        const l1 = words.slice(0, 2).join(' ');
        const l2 = words.slice(2).join(' ');
        return (
          <g key={s.label}>
            <title>{`${s.label}: ${fmtLift(s.lift)}${s.note ? ` - ${s.note}` : ''}`}</title>
            <rect x={cx - bw / 2} y={yTop} width={bw} height={padT + plotH - yTop} rx={4} style={{ fill: col }} opacity={s.confirm || first ? 1 : 0.55} />
            <text x={cx} y={yTop - 9} textAnchor="middle" fontSize={12.5} fontWeight={600} style={{ fill: col }}>{fmtLift(s.lift)}</text>
            {s.confirm ? <text x={cx} y={yTop - 24} textAnchor="middle" fontSize={14} fontWeight={700} style={{ fill: C.champion }}>{'✓'}</text> : null}
            <text x={cx} y={H - padB + 17} textAnchor="middle" fontSize={10.5} style={{ fill: C.ink }}>{l1}</text>
            {l2 ? <text x={cx} y={H - padB + 30} textAnchor="middle" fontSize={10} style={{ fill: C.ink3 }}>{l2}</text> : null}
          </g>
        );
      })}
    </svg>
  );
}

