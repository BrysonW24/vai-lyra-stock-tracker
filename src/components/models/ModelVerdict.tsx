/**
 * The Model Verdict - the post-run "does this model genuinely predict success?" surface. This is the
 * reveal a user sees after running a model: the full backtest evidence, in one place, wired to live
 * data. It is fully THEMED (v1.1.0 tokens): dark by default like the rest of the app, and the exact
 * light-glass render in the light theme - no raw-hex island. Chart colours use the semantic tokens
 * (positive/accent/negative) so contrast holds on both grounds; alpha blends use the -rgb channels.
 *
 * Honesty contract: every MEASURED number is read from src/lib/generated/model-evidence.json
 * (regenerated by the backtest `record` step); nothing numeric is hardcoded except the definitional
 * chance line (1.0x) and the labelled NORTH-STAR targets. A missing field omits its block. Backtest
 * lift is never presented as a live track record; surfacing stays shadow-live / Beta gated.
 */

const CHANCE_LIFT = 1.0; // definitional: lift is measured against chance, so the reference sits at 1.0x

// Semantic token colours - re-theme with the app (positive=champion, accent=held, negative=refuted).
const C = {
  champion: 'var(--lyra-positive)',
  challenger: 'var(--lyra-accent)',
  refuted: 'var(--lyra-negative)',
  nul: 'var(--lyra-ink-3)',
  ink: 'var(--lyra-ink)',
  ink2: 'var(--lyra-ink-2)',
  ink3: 'var(--lyra-ink-3)',
} as const;
// RGB-channel forms for alpha blends.
const R = {
  champion: 'var(--lyra-positive-rgb)',
  challenger: 'var(--lyra-accent-rgb)',
  refuted: 'var(--lyra-negative-rgb)',
  ink: 'var(--lyra-ink-rgb)',
} as const;
const alpha = (rgbVar: string, a: number) => `rgb(${rgbVar} / ${a})`;

function statusColour(status: string): string {
  if (status === 'promoted') return C.champion;
  if (status === 'refuted' || status === 'refuted_as_ranker') return C.refuted;
  return C.challenger; // challenger / challenger_not_promoted / anything held
}

function gradeColour(grade: string): string {
  const l = grade.charAt(0).toUpperCase();
  if (l === 'A') return 'var(--lyra-positive)';
  if (l === 'B') return 'var(--lyra-blue)';
  if (l === 'C') return 'var(--lyra-accent)';
  return 'var(--lyra-negative)';
}

const fmtLift = (v: number) => `${v.toFixed(2)}×`;
const fmtPct = (v: number, dp = 1) => `${(v * 100).toFixed(dp)}%`;
const nf = (n: number) => n.toLocaleString('en-US');

function champion(verdicts: EvidenceVerdict[]): EvidenceVerdict | undefined {
  return (
    verdicts.find((v) => v.model === 'champion' && v.split === 'holdout') ??
    verdicts.find((v) => v.model === 'real_v1' && v.split === 'holdout')
  );
}

